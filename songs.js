class AccompanimentTrack {
  constructor(instrument, url, notes = null) {
    this.instrument = instrument;
    this.url = url;
    this.notes = notes;
  }
}

class Arrangement {
  constructor(
    label,
    key,
    timeSignature = null,
    modulation = null,
    format = "SATB",
    pdf = null,
    chordChart = null,
    png = null,
    accompanimentTracks = [],
    tempo = null,
  ) {
    this.label = label;
    this.key = key;
    this.timeSignature = timeSignature;
    this.modulation = modulation;
    this.format = format;
    this.pdf = pdf;
    this.chordChart = chordChart;
    this.png = png;
    this.accompanimentTracks = accompanimentTracks;
    this.tempo = tempo;
  }
}

class StreamingLink {
  constructor(platform, url, albumArt = null) {
    this.platform = platform;
    this.url = url;
    this.albumArt = albumArt;
  }
}

class SongMetadata {
  constructor(
    type = "Hymn",
    tune = null,
    meter = null,
    wordsBy = null,
    musicBy = null,
  ) {
    this.type = type;
    this.tune = tune;
    this.meter = meter;
    this.wordsBy = wordsBy;
    this.musicBy = musicBy;
  }
}

class HelpfulSongInfo {
  constructor(
    about = null,
    themes = [],
    scriptureReferences = [],
    yearWritten = 2026,
    accompanimentVideoUrl = null,
    worshipVideoUrl = null,
    playableOnGuitar = false,
    recommended = false,
  ) {
    this.about = about;
    this.themes = themes;
    this.scriptureReferences = scriptureReferences;
    this.yearWritten = yearWritten;
    this.accompanimentVideoUrl = accompanimentVideoUrl;
    this.worshipVideoUrl = worshipVideoUrl;
    this.playableOnGuitar = playableOnGuitar;
    this.recommended = recommended;
  }
}

class Song {
  constructor(
    title,
    id,
    slug,
    demo_mp3 = null,
    songMetadata = new SongMetadata(),
    lyrics = [],
    arrangements = [],
    streamingLinks = [],
    helpfulSongInfo = new HelpfulSongInfo(),
  ) {
    this.title = title;
    this.id = id;
    this.slug = slug;
    this.demo_mp3 = demo_mp3;
    this.songMetadata = songMetadata;
    this.lyrics = lyrics;
    this.arrangements = arrangements;
    this.streamingLinks = streamingLinks;
    this.helpfulSongInfo = helpfulSongInfo;
    this.sheetImage = null;
    this.featured = null;
  }
}

